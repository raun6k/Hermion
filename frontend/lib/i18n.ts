export function translate(code: string, key: TextKey): string {
  return STRINGS[code]?.[key] ?? EN[key];
}

const KEY = "hermion.ui_language";

export function loadUiLanguage(): string | null {
  try {
    return localStorage.getItem(KEY);
  } catch {
    return null;
  }
}

export function saveUiLanguage(code: string): void {
  try {
    localStorage.setItem(KEY, code);
  } catch {
    // remembering the choice is a convenience
  }
}

/** The saved choice if the shop still offers it, else English if offered, else the shop's first language. */
export function pickUiLanguage(shopLanguages: string[], saved: string | null): string {
  if (saved && shopLanguages.includes(saved)) return saved;
  return shopLanguages.includes("en-IN") ? "en-IN" : (shopLanguages[0] ?? "en-IN");
}
